#!/usr/bin/env node
// PureChain rehearsal load generator / functional client.
//
// One subcommand per campaign operation; every command talks plain JSON-RPC or
// ethers v6 against the in-network node names (http://nodeN:8545) and writes
// its evidence as CSV/JSON under /artifacts.
//
// Free-gas network: every tx goes out with gasPrice 0, type-0, chainId
// 424242 — the shape real users produce.

const { ethers } = require("ethers");
const fs = require("fs");

const CHAIN_ID = 424242n;
const ART = "/artifacts";
